import { zipSync, strToU8 } from "fflate";
import type { Batch } from "./types";
export const bridgeToken = () => localStorage.getItem("rxm-bridge-token") || "";
const endpoint = "http://127.0.0.1:47851";
export interface OutlookResults {
  schemaVersion: number;
  batchId: string;
  results: { id: string; status: "Opened" | "Failed"; error?: string }[];
}
export async function checkBridge() {
  const token = bridgeToken();
  if (!token)
    throw new Error("Download and start the Outlook companion first.");
  try {
    const r = await fetch(endpoint + "/health", {
      headers: { Authorization: "Bearer " + token },
      signal: AbortSignal.timeout(3500),
    });
    if (!r.ok) throw new Error("Pairing failed");
    const data = await r.json();
    if (!data.ready) throw new Error("Bridge not ready");
    return true;
  } catch {
    throw new Error(
      "Outlook companion is not connected. Start it on this Windows PC and allow local network access if your browser asks.",
    );
  }
}
export async function openViaBridge(batch: Batch): Promise<OutlookResults> {
  await checkBridge();
  const r = await fetch(endpoint + "/open", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: "Bearer " + bridgeToken(),
    },
    body: JSON.stringify({
      schemaVersion: 1,
      batchId: batch.id,
      mails: batch.mails
        .filter((m) => m.status !== "Opened")
        .map((m) => ({
          id: m.id,
          to: m.to.email,
          cc: m.cc.map((c) => c.email),
          subject: m.subject,
          html: m.html,
        })),
    }),
    signal: AbortSignal.timeout(180000),
  });
  const data = await r.json();
  if (!r.ok || data.error)
    throw new Error(data.error || "Outlook could not open this batch");
  return data;
}
export function applyResults(batch: Batch, result: OutlookResults): Batch {
  if (
    result.schemaVersion !== 1 ||
    result.batchId !== batch.id ||
    !Array.isArray(result.results)
  )
    throw new Error("Result does not belong to this batch");
  const ids = new Set(batch.mails.map((m) => m.id));
  const seen = new Set<string>();
  for (const r of result.results) {
    if (
      !ids.has(r.id) ||
      !["Opened", "Failed"].includes(r.status) ||
      seen.has(r.id)
    )
      throw new Error("Invalid Outlook result");
    seen.add(r.id);
  }
  const map = new Map(result.results.map((r) => [r.id, r]));
  return {
    ...batch,
    mails: batch.mails.map((m) => {
      const r = map.get(m.id);
      return r ? { ...m, status: r.status, error: r.error || "" } : m;
    }),
  };
}
export async function bridgePackage() {
  const response = await fetch("/Start-Outlook-Bridge.ps1");
  if (!response.ok) throw new Error("Could not download companion source");
  const script = await response.text();
  const token =
    bridgeToken() ||
    Array.from(crypto.getRandomValues(new Uint8Array(32)))
      .map((n) => n.toString(16).padStart(2, "0"))
      .join("");
  localStorage.setItem("rxm-bridge-token", token);
  return zipSync({
    "Start-Outlook-Bridge.ps1": strToU8(script),
    "bridge-config.json": strToU8(
      JSON.stringify({ origin: location.origin, token }),
    ),
    "Start-Bridge.cmd": strToU8(
      '@echo off\r\npowershell.exe -NoProfile -STA -ExecutionPolicy Bypass -File "%~dp0Start-Outlook-Bridge.ps1"\r\n',
    ),
    "README.txt": strToU8(
    "Rx Mail Studio — Classic Outlook companion\r\n\r\n1. Extract this ZIP on your Windows PC.\r\n2. Double-click Start-Bridge.cmd. Keep its window running. No administrator permission is needed.\r\n3. In this same browser, open Settings and click Test connection. Allow local network access if your browser asks.\r\n4. Enable Also open automatically after generation if you want the companion to open editable email windows in Classic Outlook. Generation also downloads the default .eml ZIP.\r\n\r\nThe bridge accepts requests only from the app origin and the private pairing token generated by this browser. It binds only to 127.0.0.1, never the external network. Keep the ZIP and config private.\r\nIt only displays messages; it never saves or sends. Outlook may autosave open messages according to your settings. It requires Windows and Classic Outlook.\r\nIf your browser blocks local connections, use Download .eml ZIP instead.\r\nOpening results are saved in outlook-results.json. Already opened message IDs are remembered to prevent duplicate opening on retries.\r\n",
    ),
  });
}
